using CodeToDoc.Service.Interfaces;
using CodeToDoc.Service.Models;
using QuestPDF.Drawing;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace CodeToDoc.Service.Services.Documents;

/// <summary>
/// Renders a validated Markdown document to PDF using QuestPDF.
/// Output includes a cover page, a table of contents derived from actual
/// headings, page numbers, and sanitized content. Persian RTL is supported
/// when a Persian-capable font is available.
/// </summary>
public sealed class PdfDocumentRenderer : IDocumentRenderer
{
    public const string FormatName = "pdf";

    private const string DefaultFont = "Arial";
    private const string MonospaceFont = "Consolas";

    private readonly IMarkdownParser _parser;

    public PdfDocumentRenderer(IMarkdownParser parser)
    {
        _parser = parser;
    }

    static PdfDocumentRenderer()
    {
        QuestPDF.Settings.License = LicenseType.Community;
        QuestPDF.Settings.UseSystemFonts = true;
    }

    public string Format => FormatName;

    public byte[] Render(DocumentRenderInput input, CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();
        var document = _parser.Parse(input.Markdown);
        document.Title = input.Title;
        var rtl = input.Language.Equals("fa", StringComparison.OrdinalIgnoreCase);

        var fontFamily = ResolveFont(input.FontPath);

        var model = new PdfRenderModel
        {
            Document = document,
            Title = input.Title,
            Language = input.Language,
            Rtl = rtl,
            FontFamily = fontFamily,
        };

        var questDocument = QuestPDF.Fluent.Document.Create(container =>
        {
            RenderCoverPage(container, model);
            RenderBodyPages(container, model);
        });

        cancellationToken.ThrowIfCancellationRequested();
        return questDocument.GeneratePdf();
    }

    private static string ResolveFont(string? fontPath)
    {
        if (!string.IsNullOrWhiteSpace(fontPath) && File.Exists(fontPath))
        {
            try
            {
                FontManager.RegisterFontFromFile(fontPath);
            }
            catch
            {
                // Fall through to the default system font.
            }
        }

        return DefaultFont;
    }

    private static void RenderCoverPage(IDocumentContainer container, PdfRenderModel model)
    {
        container.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(2, Unit.Centimetre);
            page.DefaultTextStyle(s => s.FontFamily(model.FontFamily).FontSize(12));

            page.Content().AlignCenter().AlignMiddle().Column(column =>
            {
                column.Item().Text(model.Title).FontSize(30).Bold();
                column.Item().PaddingTop(8).Text("Generated by CodeToDoc").FontSize(13)
                    .FontColor(Colors.Grey.Darken1);
                column.Item().Text(DateTime.UtcNow.ToString("yyyy-MM-dd")).FontSize(11)
                    .FontColor(Colors.Grey.Darken2);
            });
        });
    }

    private static void RenderBodyPages(IDocumentContainer container, PdfRenderModel model)
    {
        container.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(2, Unit.Centimetre);
            page.DefaultTextStyle(s => s.FontFamily(model.FontFamily).FontSize(11));

            page.Footer().AlignCenter().Text(text =>
            {
                text.DefaultTextStyle(s => s.FontSize(9).FontColor(Colors.Grey.Darken1));
                text.Span("Page ");
                text.CurrentPageNumber();
            });

            IContainer content = page.Content();
            if (model.Rtl)
            {
                content = content.ContentFromRightToLeft();
            }

            content.Column(column =>
            {
                column.Item().Text("Table of Contents").FontSize(18).Bold();
                column.Item().PaddingTop(6).Element(c => RenderToc(c, model));
                column.Item().PageBreak();

                foreach (var block in model.Document.Blocks)
                {
                    column.Item().Element(c => RenderBlock(c, block, model));
                }
            });
        });
    }

    private static void RenderToc(IContainer container, PdfRenderModel model)
    {
        container.Column(column =>
        {
            var headings = model.Document.Headings;
            if (headings.Count == 0)
            {
                column.Item().Text("(No sections)").Italic().FontColor(Colors.Grey.Darken2);
                return;
            }

            foreach (var heading in headings)
            {
                var indent = (heading.Level - 1) * 12;
                column.Item().PaddingLeft((float)indent)
                    .Text(heading.Text)
                    .FontSize(heading.Level == 1 ? 12 : 10)
                    .FontColor(Colors.Grey.Darken3);
            }
        });
    }

    private static void RenderBlock(IContainer container, DocBlock block, PdfRenderModel model)
    {
        switch (block)
        {
            case DocHeading heading:
                container.PaddingTop(heading.Level == 1 ? 14 : 8).PaddingBottom(4)
                    .Text(heading.Text)
                    .FontSize(heading.Level == 1 ? 20 : heading.Level == 2 ? 15 : 12)
                    .Bold();
                break;

            case DocParagraph paragraph:
                container.PaddingBottom(4).Text(paragraph.Text);
                break;

            case DocCode code:
                container.PaddingBottom(6).Background(Colors.Grey.Lighten3).Padding(8)
                    .Text(code.Code)
                    .FontFamily(MonospaceFont)
                    .FontSize(9)
                    .BreakAnywhere();
                break;

            case DocQuote quote:
                container.PaddingBottom(6).PaddingLeft(8).BorderLeft(3)
                    .BorderColor(Colors.Grey.Lighten2).Padding(4)
                    .Text(quote.Text).Italic().FontColor(Colors.Grey.Darken2);
                break;

            case DocList list:
                container.PaddingBottom(6).Column(col =>
                {
                    foreach (var (item, index) in list.Items.Select((it, i) => (it, i)))
                    {
                        var prefix = list.Ordered ? $"{index + 1}. " : "\u2022 ";
                        col.Item().PaddingLeft(12).Text($"{prefix}{item}");
                    }
                });
                break;

            case DocTable table:
                RenderTable(container, table);
                break;
        }
    }

    private static void RenderTable(IContainer container, DocTable table)
    {
        if (table.Headers.Count == 0 && table.Rows.Count == 0)
        {
            return;
        }

        var columnCount = Math.Max(table.Headers.Count, table.Rows.FirstOrDefault()?.Count ?? 0);
        if (columnCount == 0)
        {
            return;
        }

        container.PaddingBottom(8).Table(tbl =>
        {
            tbl.ColumnsDefinition(cols =>
            {
                for (var i = 0; i < columnCount; i++)
                {
                    cols.RelativeColumn();
                }
            });

            if (table.Headers.Count > 0)
            {
                tbl.Header(header =>
                {
                    foreach (var cell in table.Headers)
                    {
                        header.Cell().Background(Colors.Grey.Lighten2).Padding(4)
                            .Text(cell).Bold().FontSize(10);
                    }
                });
            }

            foreach (var row in table.Rows)
            {
                for (var i = 0; i < columnCount; i++)
                {
                    var value = i < row.Count ? row[i] : string.Empty;
                    tbl.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2)
                        .Padding(4).Text(value).FontSize(10);
                }
            }
        });
    }

    private sealed class PdfRenderModel
    {
        public MarkdownDocument Document { get; init; } = new();

        public string Title { get; init; } = string.Empty;

        public string Language { get; init; } = "en";

        public bool Rtl { get; init; }

        public string FontFamily { get; init; } = DefaultFont;
    }
}
